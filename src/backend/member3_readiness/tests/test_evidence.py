class TestMultiComponentEvidence:
    def test_returns_list_of_evidence_objects(
        self,
        as1047_prediction,
        as1047_component_info,
        as1047_maintenance_overdue,
        as1047_engine_prediction,
        as1047_engine_component_info,
        as1047_engine_maintenance,
    ):
        """Test 10: build_evidence_for_asset returns one EvidenceObject per matched component."""
        predictions = [as1047_prediction, as1047_engine_prediction]
        components = [as1047_component_info, as1047_engine_component_info]
        maintenance = [as1047_maintenance_overdue, as1047_engine_maintenance]

        results = build_evidence_for_asset(predictions, components, maintenance)

        assert len(results) == 2
        assert all(isinstance(e, EvidenceObject) for e in results)

    def test_components_matched_correctly(
        self,
        as1047_prediction,
        as1047_component_info,
        as1047_maintenance_overdue,
        as1047_engine_prediction,
        as1047_engine_component_info,
        as1047_engine_maintenance,
    ):
        """Test 10b: Each EvidenceObject reflects its own component's data."""
        predictions = [as1047_prediction, as1047_engine_prediction]
        components = [as1047_component_info, as1047_engine_component_info]
        maintenance = [as1047_maintenance_overdue, as1047_engine_maintenance]

        results = build_evidence_for_asset(predictions, components, maintenance)

        bearing_evidence = next(e for e in results if e.component == "main_bearing")
        engine_evidence = next(e for e in results if e.component == "engine")

        assert bearing_evidence.failure_risk == 0.87
        assert bearing_evidence.maintenance.inspection_status == "OVERDUE"
        assert engine_evidence.failure_risk == 0.22
        assert engine_evidence.maintenance.inspection_status == "SCHEDULED"

    def test_does_not_rerun_inference(
        self,
        as1047_prediction,
        as1047_component_info,
        as1047_maintenance_overdue,
    ):
        """
        Test 10c: build_evidence_for_asset accepts a pre-fetched list and does
        not call predict_all_components() internally.
        The caller controls the prediction list — inference runs once outside.
        """
        # We pass a list with one prediction — the function must use it as-is
        results = build_evidence_for_asset(
            predictions=[as1047_prediction],
            component_info_list=[as1047_component_info],
            maintenance_info_list=[as1047_maintenance_overdue],
        )
        assert len(results) == 1
        assert results[0].failure_risk == 0.87

    def test_empty_predictions_raises_value_error(
        self, as1047_component_info, as1047_maintenance_overdue
    ):
        with pytest.raises(ValueError, match="predictions list must not be empty"):
            build_evidence_for_asset(
                predictions=[],
                component_info_list=[as1047_component_info],
                maintenance_info_list=[as1047_maintenance_overdue],
            )

    def test_empty_component_list_raises_value_error(
        self, as1047_prediction, as1047_maintenance_overdue
    ):
        with pytest.raises(ValueError, match="component_info_list must not be empty"):
            build_evidence_for_asset(
                predictions=[as1047_prediction],
                component_info_list=[],
                maintenance_info_list=[as1047_maintenance_overdue],
            )


