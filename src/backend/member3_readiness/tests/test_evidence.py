class TestInvalidFailureProbabilityRejection:
    def _make_prediction_with_prob(self, prob) -> ComponentPredictionResult:
        return ComponentPredictionResult(
            prediction_id="PRED-BAD",
            asset_id="AS-1047",
            component_id="BRG-1047",
            failure_probability=prob,
            risk_category="HIGH",
            anomaly_score=-0.5,
            anomaly_status="HIGH",
            anomaly_severity="HIGH",
            sensor="vibration",
            timestamp="2026-09-27T12:00:00+00:00",
        )

    def test_probability_above_1_rejected(
        self, as1047_component_info, as1047_maintenance_overdue
    ):
        """Test 13: failure_probability > 1.0 → EvidenceAssemblyError."""
        bad_pred = self._make_prediction_with_prob(1.01)
        with pytest.raises(EvidenceAssemblyError, match="failure_probability"):
            build_evidence(bad_pred, as1047_component_info, as1047_maintenance_overdue)

    def test_negative_probability_rejected(
        self, as1047_component_info, as1047_maintenance_overdue
    ):
        """Test 13b: failure_probability < 0.0 → EvidenceAssemblyError."""
        bad_pred = self._make_prediction_with_prob(-0.01)
        with pytest.raises(EvidenceAssemblyError, match="failure_probability"):
            build_evidence(bad_pred, as1047_component_info, as1047_maintenance_overdue)

    def test_boundary_values_accepted(
        self, as1047_component_info, as1047_maintenance_overdue
    ):
        """Test 13c: Exact boundary values 0.0 and 1.0 are valid."""
        for prob in (0.0, 1.0):
            pred = self._make_prediction_with_prob(prob)
            evidence = build_evidence(pred, as1047_component_info, as1047_maintenance_overdue)
            assert evidence.failure_risk == prob


